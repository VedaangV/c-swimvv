"""
Write a per-island benefit-cost summary file into that island's own econ
directory (data/virginia/econ/island_{id}/) -- pulled directly from
already-saved pipeline output rather than transcribed by hand from chat
history, which is unreliable and (for islands K/L/M) incomplete: the
console log line with the own-outage/switching cost breakdown was never
pasted back for those, only the per-scenario net_musd table. Both numbers
are recoverable straight from disk without rerunning anything:
- data/virginia/network/va_island_{id}.json (scripts/select_island_by_
  redistribution_sensitivity.py's output -- members, boundary_line_count,
  seed, and, for islands built by the current real-storm-scored search,
  net_score/per_storm/worst_case_total_effect/passes_real_storm_filter)
- data/virginia/econ/va_island_{id}_benefit_cost.csv (scripts/compute_
  island_benefit_cost.py's own saved output -- per-scenario diff/benefit/
  net_musd/benefit_cost_ratio for all three repair-duration variants,
  plus total_cost_musd, constant across every row for a given island).

switching_cost_musd is recomputed here from boundary_line_count using
compute_island_benefit_cost.py's own SWITCHING_COST_PER_LINE_USD constant
(kept in sync manually -- there are only two numbers involved, so a
shared-constants module felt like overkill, but if that script's default
ever changes, update the copy below too); own_outage_cost_musd is then
back-solved as total_cost_musd - switching_cost_musd, since the CSV saves
only the combined total.

Usage:
    python scripts/write_island_benefit_cost_summary.py --island g
    python scripts/write_island_benefit_cost_summary.py --all
"""

import argparse
import json

import pandas as pd

from configs import setup_logger
from configs.virginia_config import VA_ECON_DIR, VA_NETWORK_DIR, get_island_dirs

logger = setup_logger(log_file="logs/write_island_benefit_cost_summary.log")

ALL_KNOWN_ISLANDS = ["a", "b", "ab", "c", "d", "e", "f", "g", "h", "j", "k", "l", "m"]

# Must match scripts/compute_island_benefit_cost.py's SWITCHING_COST_PER_LINE_USD.
SWITCHING_COST_PER_LINE_USD = 25_000.0


def write_summary(island_id: str) -> bool:
    island_path = VA_NETWORK_DIR / f"va_island_{island_id}.json"
    bc_path = VA_ECON_DIR / f"va_island_{island_id}_benefit_cost.csv"
    if not island_path.exists() or not bc_path.exists():
        missing = island_path if not island_path.exists() else bc_path
        logger.warning(f"Island {island_id}: missing {missing}, skipping.")
        return False

    with open(island_path) as f:
        island = json.load(f)
    df = pd.read_csv(bc_path)
    if df.empty:
        logger.warning(f"Island {island_id}: {bc_path} is empty, skipping.")
        return False

    boundary_line_count = island.get("boundary_line_count", len(island.get("boundary_line_ids", [])))
    switching_cost_musd = boundary_line_count * SWITCHING_COST_PER_LINE_USD / 1e6
    total_cost_musd = float(df["total_cost_musd"].iloc[0]) if "total_cost_musd" in df.columns else float("nan")
    own_outage_cost_musd = total_cost_musd - switching_cost_musd

    mid = df[df["repair_duration_variant"] == "mid_365d"] if "repair_duration_variant" in df.columns else df
    mid = mid.set_index("scenario")
    n_positive = int((mid["net_musd"] > 0).sum())
    n_total = len(mid)

    members = island.get("members", [])
    lines = [
        f"# Island {island_id.upper()} — Benefit-Cost Summary",
        "",
        f"Auto-generated by `scripts/write_island_benefit_cost_summary.py` from "
        f"`va_island_{island_id}.json` and `va_island_{island_id}_benefit_cost.csv` -- "
        "do not hand-edit; rerun the script after any pipeline rerun for this island.",
        "",
        "## Topology",
        f"- Members ({island.get('member_count', len(members))}): {members}",
        f"- Seed: {island.get('seed')}",
        f"- Boundary lines cut: {boundary_line_count}",
    ]
    if "net_score" in island:
        lines.append(f"- Search net_score: {island['net_score']:.4f}")
    if "worst_case_total_effect" in island:
        lines.append(
            f"- Worst-case real-storm total effect at search time, cheap-draw approximation "
            f"(Phase 6i): {island['worst_case_total_effect']:.6f}"
        )
    if "final_island_passes_real_storm_filter" in island:
        lines.append(
            f"- Passed Phase 6i hard real-storm filter at search time: "
            f"{island['final_island_passes_real_storm_filter']}"
        )
    if "stop_reason" in island:
        lines.append(f"- Growth stop reason: {island['stop_reason']}")

    lines += [
        "",
        "## One-time costs",
        f"- Switching cost: ${switching_cost_musd:.4f}M ({boundary_line_count} lines x "
        f"${SWITCHING_COST_PER_LINE_USD:,.0f}/line)",
        f"- Own-outage cost: ${own_outage_cost_musd:.4f}M",
        f"- **Total one-time cost: ${total_cost_musd:.4f}M**",
        "",
        "## Net benefit by scenario (mid_365d repair-duration variant, $M)",
        "",
        "```",
        mid[["diff_per_day_musd", "total_benefit_musd", "net_musd", "benefit_cost_ratio"]].to_string(),
        "```",
        "",
        f"**{n_positive}/{n_total} scenarios net-positive after switching + own-outage cost.**",
    ]

    per_storm = island.get("per_storm")
    if per_storm:
        lines += [
            "",
            "## Per-storm search-time fragility-weighted total effect",
            "(own_effect + redistribution_cost_real, positive = worse for whole Virginia; "
            "this is the search's own cheap-draw approximation, not the full real pipeline result "
            "already reflected in the scenario table above)",
            "",
        ]
        for storm, v in per_storm.items():
            total_effect = v.get("own_effect", float("nan")) + v.get("redistribution_cost_real", float("nan"))
            lines.append(f"- {storm}: {total_effect:+.6f}")

    out_dir = get_island_dirs(island_id)["econ_dir"]
    out_path = out_dir / "BENEFIT_COST_SUMMARY.md"
    out_path.write_text("\n".join(lines) + "\n")
    logger.info(f"Saved {out_path}")
    return True


def main(island_ids):
    written = [i for i in island_ids if write_summary(i)]
    logger.info(f"Wrote summaries for {len(written)}/{len(island_ids)} island(s): {written}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Write a per-island benefit-cost summary (BENEFIT_COST_SUMMARY.md) into that island's own econ folder."
    )
    parser.add_argument("--island", type=str, default=None, help="Single island id, e.g. 'g'.")
    parser.add_argument("--all", action="store_true", help=f"Run for all known islands: {ALL_KNOWN_ISLANDS}")
    args = parser.parse_args()
    if args.all:
        main(ALL_KNOWN_ISLANDS)
    elif args.island:
        main([args.island])
    else:
        parser.error("Pass --island <id> or --all")
